#!/usr/bin/env node
/**
 * TURN A LIVE WORKSPACE'S BOARDS INTO TEMPLATES.
 *
 * Reads a workspace document (the `data` of GET /api/workspace, or the
 * `workspace_preferences` row) and writes client/src/data/boardTemplates.ts:
 * every global board as a template with the same widgets, in the same order,
 * at the same widths, with the same cards in the details section.
 *
 * WHAT DOES NOT CARRY OVER is what belongs to one owner: `param` (a venture id
 * or a fleet account id) and `hidden` (fleet account ids). A board that pins
 * the same card to nine servers becomes a template with that card once,
 * unpinned — the card's header asks which server, exactly as the palette does.
 *
 *   node scripts/export-board-templates.mjs <workspace.json>
 *
 * Pulling the Pi's copy:
 *   ssh pi@<pi> 'cd /opt/onepersoncompany/server && node -e "…SELECT data FROM
 *   workspace_preferences WHERE id=1…"' > workspace.json
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const file = process.argv[2];
if (!file) {
  console.error("usage: node scripts/export-board-templates.mjs <workspace.json>");
  process.exit(1);
}
const raw = JSON.parse(readFileSync(file, "utf8"));
const doc = raw.data ?? raw;
const boards = (doc.dashboards ?? []).filter((d) => !d.ventureId);

/* One line on each board, for the template card. A board this list does not
   name still exports, with a count for its note. */
const NOTES = {
  overview: "the morning read: ARR, net, views, collections, expenses, fleet and what needs you",
  servers: "fleet health, Hetzner spend and specs, uptime and one box in detail",
  domains: "registrars, expiry, renewals and DNS across every domain",
  revenue: "MRR, collections, movement, churn and every payment source",
  search: "Search Console clicks and impressions across the portfolio",
  traffic: "visitors, views and Cloudflare traffic by site",
  analytics: "Umami visitors, pages, referrers, countries and events",
  seo: "rankings, striking distance, zero-click queries and indexing",
  social: "followers, top and latest posts on every network",
  ads: "spend, delivery, creatives and quick wins",
  demand: "what people are asking for, thread by thread",
  development: "commits, stars, releases and traffic on every repo",
  apps: "App Store and Google Play ratings, reviews and payouts",
  users: "sign-ups and active users across every product",
  costs: "all-in monthly spend: servers, services, power, domains, LLMs",
  "llm-usage": "the apps' LLM bills apart from One Person Company's own usage",
};

/* Board slug → template id. The Pi's LLM board is the owner's own (slug
   llm-usage); the rest keep their slug, which replaces the older preset of the
   same id. */
const idFor = (slug) => (slug === "llm-usage" ? "llm" : slug);

const templates = boards.map((d) => {
  const seen = new Set();
  const widgets = [];
  for (const w of d.widgets) {
    if (w.param) {
      /* Pinned: keep the first of each type, unpinned. */
      if (seen.has(w.type)) continue;
      seen.add(w.type);
    }
    const out = { type: w.type, w: w.w };
    if (w.span) out.span = w.span;
    if (w.detail) out.detail = true;
    widgets.push(out);
  }
  return {
    id: idFor(d.slug),
    label: d.name,
    note: NOTES[d.slug] ?? `${widgets.length} widgets`,
    widgets,
  };
});

/* One widget a line, so a diff after a re-export reads as the board changed. */
const str = (v) => JSON.stringify(v);
const widget = (w) =>
  `{ ${Object.entries(w).map(([k, v]) => `${k}: ${k === "detail" ? v : str(v)}`).join(", ")} }`;
const render = (t) => `  {
    id: ${str(t.id)},
    label: ${str(t.label)},
    note: ${str(t.note)},
    widgets: [
${t.widgets.map((w) => `      ${widget(w)},`).join("\n")}
    ],
  },`;

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "..", "client", "src", "data", "boardTemplates.ts");
const body = `/* GENERATED by scripts/export-board-templates.mjs from the owner's live
   workspace — do not edit by hand; re-run the script after the boards change.
   Every global board, in the owner's order, as a template: same widgets, same
   order, same widths, same details section. Per-server and per-venture pins
   are owner-specific and are kept once, unpinned. */
import type { PresetWidget } from "./widgets.ts";

export const BOARD_TEMPLATES: {
  id: string;
  label: string;
  note: string;
  widgets: PresetWidget[];
}[] = [
${templates.map(render).join("\n")}
];
`;
writeFileSync(target, body);
console.log(`wrote ${templates.length} templates to ${target}`);
for (const t of templates) console.log(`  ${t.id.padEnd(12)} ${t.widgets.length} widgets`);
