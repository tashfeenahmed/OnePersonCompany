/** Names that mean a brand we hold but do not spell the same way. Only
 *  entries seen in a real feed or one obvious release away: a guess here puts
 *  the wrong company's logo next to real money. */
const ALIASES: Record<string, string> = {
  alibaba: "alibabacloud",
  "google-vertex": "google",
  "google-ai-studio": "google",
  "google-cloud": "google",
  "meta-llama": "meta",
  mistral: "mistralai",
  "x-ai": "x",
  xai: "x",
};

/**
 * The family a bare model name belongs to, for the ledgers this box writes
 * itself, where a backend reports "gemini-3.7-flash" with no house in front
 * of it. First match wins; the list is short on purpose and a name it does
 * not know becomes a monogram, not a guess.
 */
const FAMILIES: [RegExp, string][] = [
  [/^(gpt|o[1-9]\b|chatgpt|text-embedding|dall-e|whisper)/, "openai"],
  [/^(gemini|gemma|palm)/, "google"],
  [/^claude/, "anthropic"],
  [/^(llama|meta)/, "meta"],
  [/^(mistral|mixtral|codestral|ministral)/, "mistralai"],
  [/^deepseek/, "deepseek"],
  [/^(qwen|qwq)/, "qwen"],
  [/^grok/, "x"],
  [/^(sonar|pplx)/, "perplexity"],
  [/^nemotron/, "nvidia"],
];

/**
 * The brand behind a model or provider name.
 *
 * An OpenRouter slug is `house/detail` — `google/gemini-3.7-flash`,
 * `google-vertex/eu` — so the part before the slash is the company. A bare
 * name from this box's own ledger has no slash and is placed by its family.
 */
export function modelHouse(name: string): string {
  const lower = name.toLowerCase().trim();
  if (lower.includes("/")) {
    const head = lower.split("/")[0]!.trim();
    return ALIASES[head] ?? head;
  }
  for (const [re, house] of FAMILIES) if (re.test(lower)) return house;
  return lower.split(/[^a-z0-9]+/)[0] || "?";
}

/** Two letters, for the tile that stands in for a mark we do not have. */
export function monogram(house: string): string {
  const letters = house.replace(/[^a-z0-9]/gi, "");
  return letters.slice(0, 2).toUpperCase() || "?";
}
